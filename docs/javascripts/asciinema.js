/* Terminal recordings, played by asciinema-player from .cast files kept under
   docs/assets/casts/ (generated by tools/media/cast.py). Ported from
   depictio-docs (MIT) docs/javascripts/asciinema.js at 1610ed8.

   The player stylesheet is loaded from mkdocs.yml (extra_css); its script
   (about 185 KB) is fetched from jsDelivr only on a page that has a cast.

   Embed one with

     <div class="asciinema-cast" data-cast="assets/casts/<name>.cast"></div>

   data-cast is relative to the docs root, so the same markup works on any
   page. It is resolved against the site root, which Material's #__config gives
   relative to the page first loaded: resolved once here, it stays right on the
   pages navigation.instant swaps in later, under a mike version prefix such as
   /spectio/0.3/, and with `mkdocs serve`.

   Optional attributes: data-poster (default "npt:0:3"), data-theme (default
   "spectio", see stylesheets/asciinema.css), data-idle-time-limit (default 1.5),
   data-autoplay ("true" to start on load, used by combined captures).

   With navigation.instant, players are mounted on every page swap through
   document$, and the players of the page left behind are disposed of first. */
const SITE_ROOT = (() => {
  const config = document.getElementById('__config');
  const base = config ? JSON.parse(config.textContent).base : '.';
  return new URL(`${base}/`, window.location.href);
})();

const PLAYER_JS =
  'https://cdn.jsdelivr.net/npm/asciinema-player@3.17.0/dist/bundle/asciinema-player.min.js';

let castPlayers = [];
let playerLoading = null;

function loadPlayer() {
  if (typeof AsciinemaPlayer !== 'undefined') return Promise.resolve();
  if (!playerLoading) {
    playerLoading = new Promise((resolve, reject) => {
      const script = document.createElement('script');
      script.src = PLAYER_JS;
      script.onload = resolve;
      script.onerror = () => {
        playerLoading = null;
        reject(new Error(`Could not load ${PLAYER_JS}`));
      };
      document.head.appendChild(script);
    });
  }
  return playerLoading;
}

async function mountCasts() {
  castPlayers.forEach((player) => player.dispose());
  castPlayers = [];

  const casts = document.querySelectorAll('.asciinema-cast[data-cast]');
  if (casts.length === 0) return;
  await loadPlayer();

  casts.forEach((el) => {
    // The reader may have left the page while the player script was loading.
    if (!el.isConnected) return;
    const { cast, poster, theme, idleTimeLimit, autoplay } = el.dataset;
    el.replaceChildren();
    castPlayers.push(
      AsciinemaPlayer.create(new URL(cast, SITE_ROOT).href, el, {
        fit: 'width',
        poster: poster || 'npt:0:3',
        theme: theme || 'spectio',
        idleTimeLimit: Number(idleTimeLimit) || 1.5,
        autoPlay: autoplay === 'true',
      }),
    );
  });
}

if (typeof document$ !== 'undefined') {
  document$.subscribe(mountCasts);
} else {
  document.addEventListener('DOMContentLoaded', mountCasts);
}
